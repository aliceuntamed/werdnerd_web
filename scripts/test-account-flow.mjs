await context.route('**/auth/v1/**', async route => {
  const request = route.request();
  const url = new URL(request.url());
  const body = request.postDataJSON();
  const respond = (json, status = 200) => route.fulfill({ status, contentType: 'application/json', headers: { 'x-supabase-api-version': '2024-01-01', 'access-control-expose-headers': 'x-supabase-api-version' }, json: { ...json, ...(json.code ? { error_code: json.code } : {}) } });
  if (url.pathname.endsWith('/token')) return failLogin ? respond({ code: 'invalid_credentials', message: 'Internal detail should not be shown' }, 400) : respond(session());
  if (url.pathname.endsWith('/signup')) { signupRequests++; signupRedirect = url.searchParams.get('redirect_to'); return respond({ ...user, identities: [] }); }
  if (url.pathname.endsWith('/recover')) { recoveryRequests++; recoveryRedirect = url.searchParams.get('redirect_to'); return respond({}); }
  if (url.pathname.endsWith('/resend')) {
    resendRequests++;
    resendRedirect = url.searchParams.get('redirect_to');
    assert.equal(body.type, 'signup');
    assert.equal(body.email, user.email);
    assert.equal(body.password, undefined, 'Resending must not submit a password');
    await new Promise(resolve => setTimeout(resolve, 120));
    return failResend ? respond({ code: 'over_email_send_rate_limit', message: 'Internal rate limit detail' }, 429) : respond({});
  }
  if (url.pathname.endsWith('/logout')) return failSignOut ? respond({ code: 'unexpected_failure', message: 'Mock sign-out failure' }, 400) : respond({});
  if (url.pathname.endsWith('/user')) {
    if (request.method() === 'PUT' && body?.data) user.user_metadata = { ...user.user_metadata, ...body.data };
    if (request.method() === 'PUT' && body?.password) passwordUpdates++;
    return respond(user);
  }
  return respond({});
});
await context.route('**/rest/v1/**', async route => {
  const request = route.request();
  const url = new URL(request.url());
  const respond = (json, status = 200) => route.fulfill({ status, contentType: 'application/json', json });
  if (url.pathname.endsWith('/werds')) return respond([werd]);
  if (url.pathname.endsWith('/favorites')) {
    if (request.method() === 'GET') { favoriteReads++; return failRead ? respond({ message: 'Mock read failure' }, 403) : respond(favorites); }
    saveRequests++;
    if (failSave) return respond({ message: 'Mock write failure' }, 403);
    if (request.method() === 'POST') favorites = [{ werd_id: werd.werd_id, created_at: new Date().toISOString(), werd }];
    if (request.method() === 'DELETE') favorites = [];
    return respond({});
  }
  return respond([]);
});

